import test from'node:test';
import assert from'node:assert/strict';
import{readFile}from'node:fs/promises';
import{approvedShoppingOrder,purchasedItem,shoppingGroups,shoppingPartKey}from'../src/shopping-checklist-data.js';

test('lista de compras usa as peças da O.S. em execução e calcula o progresso',()=>{
  const orders=[{id:'o1',number:'127',status:'Em andamento',client:{name:'Cliente Teste'},vehicle:{plate:'ABC1D23',model:'Gol'},budget:{parts:[{description:'Filtro',supplier:'Luizinho',cost:30},{description:'Óleo',supplier:'Auto Peças Sul',cost:25,quantity:2},{description:'Correia',supplier:'Distribuidora Centro',cost:80}]}}],checklists=[{orderId:'o1',items:{'filtro:1':{purchased:true,purchasedBy:{name:'Fabiano'}},'correia:1':{purchasedAt:'2026-10-23T11:00:00Z'}}}],groups=shoppingGroups(orders,checklists);
  assert.equal(groups.length,1);
  assert.equal(groups[0].client.name,'Cliente Teste');
  assert.equal(groups[0].total,3);
  assert.equal(groups[0].purchased,2);
  assert.equal(groups[0].pending,1);
  assert.equal(groups[0].totalCost,160);
  assert.equal(groups[0].purchasedCost,110);
  assert.equal(groups[0].pendingCost,50);
  assert.equal(groups[0].items[0].supplier,'Luizinho');
  assert.equal(groups[0].items[1].costTotal,50);
  assert.equal(purchasedItem(groups[0].items[1]),false);
  assert.equal(groups[0].items[2].partKey,'correia:1');
});

test('Compras usa chave estável, ignora recusadas e respeita exclusões do checklist',()=>{
  const parts=[{code:'ABC-1',description:'Filtro',supplier:'Fornecedor A',cost:12.5},{description:'Óleo',cost:20},{description:'Óleo',cost:22},{description:'Peça recusada',cost:90,refused:true}];
  assert.equal(shoppingPartKey(parts[0],0,parts),'abc 1:1');
  assert.equal(shoppingPartKey(parts[2],2,parts),'oleo:2');
  const groups=shoppingGroups([{id:'o1',number:'10',status:'Em andamento',budget:{parts}}],[{orderId:'o1',items:{'oleo:1':{excluded:true}}}]);
  assert.equal(groups[0].total,2);
  assert.deepEqual(groups[0].items.map(item=>item.description),['Filtro','Óleo']);
  assert.equal(groups[0].items[0].supplier,'Fornecedor A');
  assert.equal(groups[0].items[1].supplier,'Fornecedor não informado');
  assert.equal(groups[0].totalCost,34.5);
});

test('Compras mostra somente O.S. aprovadas',()=>{
  assert.equal(approvedShoppingOrder({status:'Aguardando diagnóstico'}),false);
  assert.equal(approvedShoppingOrder({status:'Aguardando aprovação'}),false);
  assert.equal(approvedShoppingOrder({status:'Orçamento fora do pátio'}),false);
  assert.equal(approvedShoppingOrder({status:'Recusado'}),false);
  assert.equal(approvedShoppingOrder({status:'Em andamento'}),true);
  assert.equal(approvedShoppingOrder({status:'Aguardando peça'}),false);
  assert.equal(approvedShoppingOrder({status:'Pronto para entrega'}),false);
  assert.equal(approvedShoppingOrder({status:'Entregue'}),false);
  assert.equal(approvedShoppingOrder({status:'Em andamento',budget:{approved:false}}),false);
  assert.equal(approvedShoppingOrder({status:'Aguardando aprovação',budget:{approved:true}}),false);
  assert.equal(approvedShoppingOrder({status:'Em andamento',budget:{approved:true}}),true);
  const groups=shoppingGroups([{id:'approved',status:'Em andamento',budget:{parts:[{description:'Filtro'}]}},{id:'pending',status:'Aguardando aprovação',budget:{parts:[{description:'Óleo'}]}}]);
  assert.deepEqual(groups.map(group=>group.orderId),['approved']);
});

